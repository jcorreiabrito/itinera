def get_i18n(lang: str | None = "en") -> Dict[str, str]:
    """Get the dictionary for a locale, defaulting to 'en'."""
    normalized = "pt-BR" if lang and lang.lower().replace("-", "_").startswith("pt") else "en"
    return TRANSLATIONS.get(normalized, TRANSLATIONS["en"])
